#!/usr/bin/env node
/**
 * Builds the airports seed migration from OurAirports (public domain):
 *   curl -sSfL -o /tmp/ourairports.csv https://davidmegginson.github.io/ourairports-data/airports.csv
 *   node scripts/generate-airports-seed.mjs /tmp/ourairports.csv > nhost/migrations/default/<ts>_airports_seed/up.sql
 *
 * Keeps large + medium airports with scheduled service and an IATA code. OurAirports has no time zones,
 * so `tz` comes from the app's curated list (crew-up-app/constants/airports.ts) where available.
 */
import { readFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const csvPath = process.argv[2];
if (!csvPath) {
  console.error('usage: generate-airports-seed.mjs <airports.csv>');
  process.exit(1);
}

function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = '';
  let quoted = false;
  for (let i = 0; i < text.length; i += 1) {
    const char = text[i];
    if (quoted) {
      if (char === '"' && text[i + 1] === '"') {
        field += '"';
        i += 1;
      } else if (char === '"') quoted = false;
      else field += char;
    } else if (char === '"') quoted = true;
    else if (char === ',') {
      row.push(field);
      field = '';
    } else if (char === '\n') {
      row.push(field);
      rows.push(row);
      row = [];
      field = '';
    } else if (char !== '\r') field += char;
  }
  if (field || row.length) rows.push([...row, field]);
  return rows;
}

const sql = (value) => (value ? `'${value.replace(/'/g, "''")}'` : 'NULL');

const appAirports = await readFile(path.resolve(here, '../../crew-up-app/constants/airports.ts'), 'utf8').catch(
  () => '',
);
const curatedTz = new Map(
  [...appAirports.matchAll(/iata: '([A-Z]{3})'[^}]*timeZone: '([^']+)'/g)].map((match) => [match[1], match[2]]),
);

const [header, ...records] = parseCsv(await readFile(csvPath, 'utf8'));
const col = Object.fromEntries(header.map((name, index) => [name, index]));

const airports = new Map();
for (const record of records) {
  const iata = record[col.iata_code]?.trim().toUpperCase();
  const type = record[col.type];
  if (!iata || !/^[A-Z]{3}$/.test(iata)) continue;
  if (record[col.scheduled_service] !== 'yes') continue;
  if (type !== 'large_airport' && type !== 'medium_airport') continue;
  const existing = airports.get(iata);
  if (existing && existing.type === 'large_airport') continue;
  airports.set(iata, {
    type,
    iata,
    icao: record[col.icao_code]?.trim() || record[col.gps_code]?.trim() || null,
    name: record[col.name].trim(),
    city: record[col.municipality]?.trim() || null,
    country: record[col.iso_country]?.trim().toUpperCase() || null,
  });
}

const values = [...airports.values()]
  .sort((a, b) => a.iata.localeCompare(b.iata))
  .map(
    (airport) =>
      `  (${sql(airport.iata)}, ${sql(airport.icao)}, ${sql(airport.name)}, ${sql(airport.city)}, ${sql(
        airport.country,
      )}, ${sql(curatedTz.get(airport.iata) ?? null)}, ${airport.type === 'large_airport'})`,
  );

process.stdout.write(`-- CrewUp — airports reference seed (generated by scripts/generate-airports-seed.mjs)
-- Source: OurAirports (https://ourairports.com/data/, public domain). ${values.length} airports:
-- large + medium with scheduled service and an IATA code. tz from the app's curated list where known.

INSERT INTO public.airports (iata, icao, name, city, country_code, tz, is_major) VALUES
${values.join(',\n')}
ON CONFLICT (iata) DO UPDATE SET
  icao = EXCLUDED.icao,
  name = EXCLUDED.name,
  city = EXCLUDED.city,
  country_code = EXCLUDED.country_code,
  tz = COALESCE(public.airports.tz, EXCLUDED.tz),
  is_major = EXCLUDED.is_major;
`);
